const express = require('express')
const mongoose = require('mongoose')
const cors = require('cors')
const cookieParser = require('cookie-parser')
const helmet = require('helmet')
const morgan = require('morgan')
const rateLimit = require('express-rate-limit')
const path = require('node:path')
const { clientOrigin, uploadDir } = require('./config/env')
const authRoutes = require('./routes/auth-routes')
const interviewRoutes = require('./routes/interview-routes')
const profileRoutes = require('./routes/profile-routes')
const { errorHandler } = require('./middleware/error-handler')
const { isConfigured: cloudinaryConfigured } = require('./config/cloudinary')

const app = express()
app.use(helmet())
app.use(cors({ origin: clientOrigin, credentials: true }))
app.use(cookieParser())
app.use(express.json({ limit: '1mb' }))
app.use(morgan('tiny'))
app.use(rateLimit({ windowMs: 60 * 1000, limit: 120 }))
app.use(`/${uploadDir}`, express.static(path.resolve(process.cwd(), uploadDir)))
app.get('/health', (req, res) => res.json({ service: 'nexora-api', status: 'ok', timestamp: new Date().toISOString(), database: mongoose.connection.readyState === 1 ? 'connected' : 'fallback', cloudinary: cloudinaryConfigured ? 'configured' : 'missing' }))
app.use('/api/auth', authRoutes)
app.use('/api/interviews', interviewRoutes)
app.use('/api/profile', profileRoutes)
app.use(errorHandler)

module.exports = app
